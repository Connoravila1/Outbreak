// Builds src/ui/icon-data.ts: a subset of @iconify-json/game-icons so the bundle
// ships ~70 icons instead of ~4000. Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json');

const NAMES = [
  // tabs and chrome
  'treasure-map', 'backpack', 'checklist', 'crossed-swords', 'person', 'gps', 'gears',
  'speaker', 'speaker-off', 'vibrating-smartphone', 'padlock', 'key', 'hourglass', 'stopwatch',
  // world things
  'shambling-zombie', 'wolf-howl', 'fist', 'screaming', 'imp', 'hooded-assassin', 'rifle',
  'barricade', 'ammo-box', 'cardboard-box-closed', 'parachute', 'ghost', 'castle', 'skull-crack',
  'all-seeing-eye', 'radar-sweep', 'biohazard', 'death-skull', 'tombstone', 'pirate-skull',
  // gear and consumables
  'baseball-bat', 'hoodie', 'flashlight', 'spiked-bat', 'leather-armor', 'armor-vest', 'shield',
  'claw-slashes', 'fangs', 'tooth', 'bone-knife', 'syringe', 'health-potion', 'bandage-roll',
  'medical-pack', 'heart-plus', 'meat', 'brain', 'eyeball', 'coins', 'anvil', 'recycle',
  // stats and reward
  'heart-beats', 'biceps', 'sprint', 'lightning-helix', 'flame', 'trophy', 'laurels', 'crown',
  'star-medal', 'boot-prints', 'target-dummy', 'swords-emblem', 'lantern', 'ringing-alarm',
  'plain-circle', 'bullseye', 'compass', 'thorny-vine', 'swap-bag', 'wooden-crate',
  // game screens
  'upgrade', 'chat-bubble', 'trash-can', 'check-mark', 'exit-door', 'magnifying-glass', 'shop',
  'scroll-unfurled', 'three-friends', 'cancel', 'info', 'flame-claws', 'sands-of-time',
  'broken-heart', 'id-card', 'cash', 'sword-wound', 'funnel', 'pill', 'heart-bottle',
  // real places, time of day
  'shopping-cart', 'hammer-nails', 'gas-pump', 'police-badge', 'knife-fork', 'shirt', 'sun', 'moon',
];

const out = {};
for (const n of NAMES) {
  const ic = set.icons[n];
  if (!ic) throw new Error('missing icon ' + n);
  out[n] = ic.body;
}
const body =
  '// GENERATED by scripts/gen-icons.mjs from @iconify-json/game-icons (CC BY 3.0, game-icons.net).\n' +
  '// Do not edit by hand. 512x512 viewBox, single-path bodies using currentColor.\n' +
  'export const ICON_VIEWBOX = 512;\n' +
  'export const ICONS: Record<string, string> = ' + JSON.stringify(out, null, 1) + ';\n' +
  'export type IconName = ' + NAMES.map((n) => `'${n}'`).join(' | ') + ';\n';
writeFileSync(new URL('../src/ui/icon-data.ts', import.meta.url), body);
console.log('wrote', NAMES.length, 'icons');
